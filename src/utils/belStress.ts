export function applyBelarusianStress(rawWord: string): string {
  if (!rawWord) return '';

  // Калі націск ужо пастаўлены карыстальнікам альбо базай
  if (rawWord.includes('\u0301')) {
    return rawWord;
  }
  if (rawWord.includes('+')) {
    return rawWord.replace(/\+/g, '\u0301');
  }
  if (rawWord.includes('\u00B4')) {
    return rawWord.replace(/\u00B4/g, '\u0301');
  }

  const clean = rawWord.trim();
  const lower = clean.toLowerCase();

  // Ненаціскныя службовыя словы і прыназоўнікі
  if (NIENACISKNYJA.has(lower)) {
    return clean;
  }

  // 1. Праверка па слоўніку
  if (BELARUSIAN_STRESS_DICT[lower]) {
    const stressed = BELARUSIAN_STRESS_DICT[lower];
    if (clean[0] === clean[0].toUpperCase() && clean[0] !== clean[0].toLowerCase()) {
      return stressed[0].toUpperCase() + stressed.slice(1);
    }
    return stressed;
  }

  // 2. Літара "ё" у беларускай мове ЗАЎСЁДЫ пад націскам
  if (lower.includes('ё')) {
    let res = '';
    for (let i = 0; i < clean.length; i++) {
      res += clean[i];
      if (clean[i].toLowerCase() === 'ё') {
        res += '\u0301';
      }
    }
    return res;
  }

  // 3. Калі ў слове толькі адзін галосны — ён заўсёды пад націскам
  if (countVowels(clean) === 1) {
    for (let i = 0; i < clean.length; i++) {
      if (/[аеіоуыэюяАЕІОУЫЭЮЯ]/.test(clean[i])) {
        return clean.slice(0, i + 1) + '\u0301' + clean.slice(i + 1);
      }
    }
  }

  // 4. Літара "о" у спрадвечна беларускіх словах практычна заўсёды пад націскам
  if (lower.includes('о')) {
    const pO = lower.indexOf('о');
    return clean.slice(0, pO + 1) + '\u0301' + clean.slice(pO + 1);
  }

  // 5. Разбор складаных слоў з прэфіксоідамі (аўта-, мікра-, тэле-, і г.д.)
  const PREFIXOID_REGEX = /^(аўта|мікра|тэле|радыё|фота|кіна|электра|мота|вела|авія|полі|супер|гіпер|паў)([а-яёіў]+)$/i;
  const prefMatch = clean.match(PREFIXOID_REGEX);
  if (prefMatch) {
    const pfx = prefMatch[1];
    const stem = prefMatch[2];
    const stressedStem = applyBelarusianStress(stem);
    if (stressedStem.includes('\u0301')) {
      return pfx + stressedStem;
    }
  }

  // 6. Назоўнікі з суфіксамі -чык, -шчык (-чыка, -шчыка, -чыкі, -шчыкі)
  if (/[чш]ык[а-яёіў]*$/i.test(clean)) {
    const idx = clean.search(/[аеіоуыэюя][тдзс]?[чш]ык[а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.1. Назоўнікі памяншальна-ласкальныя на -ачка, -ечка, -эчка, -ічка, -ычка, -ячка (саба́чка, сястры́чка)
  if (/[аеэяіы]чк[а-яёіў]*$/i.test(clean)) {
    const idx = clean.search(/[аеэяіы]чк[а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.2. Назоўнікі на -інка, -ынка (дзяўчы́нка, сцяжы́нка, хваі́нка)
  if (/[іы]нк[а-яёіў]*$/i.test(clean)) {
    const idx = clean.search(/[іы]нк[а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.3. Прыметнікі з суфіксамі -аты, -яты (пухна́ты, вуса́ты, рага́ты, кудла́ты, грыва́ты)
  if (/[ая]т[ыаеуюі][а-яёіў]*$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[ая]т[ыаеуюі][а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.4. Прыметнікі з суфіксамі -істы, -ысты (серабры́сты, цяні́сты)
  if (/[іы]ст[ыаеуюі][а-яёіў]*$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[іы]ст[ыаеуюі][а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.5. Прыметнікі з суфіксамі -іны, -ыны (лебядзі́ны, сакалі́ны, жураўлі́ны, птушы́ны, качы́ны)
  if (/[іы]н([ыаеуюі]|[ыаоі]га|[ыаоі]му|[ыаоі]м|[ыаоі]й|[ыаоі]ю|[ыаоі]мі|[ыаоі]х)$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[іы]н([ыаеуюі]|[ыаоі]га|[ыаоі]му|[ыаоі]м|[ыаоі]й|[ыаоі]ю|[ыаоі]мі|[ыаоі]х)$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.6. Дзеясловы цяперашняга/будучага часу на -ае, -аеш, -аем, -аеце, -аюць, -аецца, -аешся, -аемся, -аецеся, -аюцца
  if (/[ая](е|еш|ем|еце|юць|ецца|ешся|емся|ецеся|юцца)$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[ая](е|еш|ем|еце|юць|ецца|ешся|емся|ецеся|юцца)$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.7. Дзеясловы 1-га спражэння на -е́цца, -э́цца, -е́шся, -э́шся, -е́ўся, -е́цеся, -э́цеся
  // (трасе́цца, нясе́цца, бярэ́цца, вядзе́цца, кладзе́цца, ідзе́цца, пячэ́цца, грызе́цца, стрыжэ́цца, цвіце́цца, жыве́цца, плыве́цца)
  if (/[^аяёеэіоуы][еэ](цца|шся|мся|цеся)$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[еэ](цца|шся|мся|цеся)$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 6.8. Дзеясловы 1-га спражэння 3-й асобы множнага ліку на -у́цца / -у́ць (трасу́цца, нясу́цца, бяру́цца, вяду́цца, кладу́цца)
  if (/(трас|няс|бяр|вяд|клад|ід|пяк|грыз|стрыг|цвіт|жыв|плыв|дзяр|жэр|пас|таўк|плят|мят|кур|сяч)(у)(ць|цца|ся|м)?$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/у(ць|цца|ся|м)?$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 7. Дзеясловы загаднага ладу на -ай, -айце, -ей, -ейце, -уй, -уйце
  if (/[аеэя]й$/i.test(clean)) {
    const idx = clean.search(/[аеэя]й$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[аеэя]йце$/i.test(clean)) {
    const idx = clean.search(/[аеэя]йце$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/уй$/i.test(clean)) {
    return clean.replace(/уй$/i, 'у\u0301й');
  }
  if (/уйце$/i.test(clean)) {
    return clean.replace(/уйце$/i, 'у\u0301йце');
  }

  // 9. Дзеяслоўныя суфіксы і формы
  // -аваць, -яваць, -іраваць, -ыраваць
  if (/аваць$/i.test(clean)) {
    return clean.replace(/аваць$/i, 'а\u0301ваць');
  }
  if (/яваць$/i.test(clean)) {
    return clean.replace(/яваць$/i, 'я\u0301ваць');
  }
  if (/аваў$/i.test(clean)) {
    return clean.replace(/аваў$/i, 'а\u0301ваў');
  }
  if (/авала$/i.test(clean)) {
    return clean.replace(/авала$/i, 'а\u0301вала');
  }
  if (/авалі$/i.test(clean)) {
    return clean.replace(/авалі$/i, 'а\u0301валі');
  }
  if (/учы$/i.test(clean)) {
    return clean.replace(/учы$/i, 'у\u0301чы');
  }
  if (/ючы$/i.test(clean)) {
    return clean.replace(/ючы$/i, 'ю\u0301чы');
  }
  if (/ўшы$/i.test(clean)) {
    const idx = clean.search(/[аеіоуыэюя]ўшы$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 10. Суфіксы прыметнікаў
  // -ейшы, -эйшы, -айшы, -яйшы (вышэйшая ступень: прыгажэйшы, хутчэйшы)
  if (/[аеэя]йшы$/i.test(clean)) {
    const idx = clean.search(/[аеэя]йшы$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[аеэя]йшая$/i.test(clean)) {
    const idx = clean.search(/[аеэя]йшая$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[аеэя]йшае$/i.test(clean)) {
    const idx = clean.search(/[аеэя]йшае$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[аеэя]йшыя$/i.test(clean)) {
    const idx = clean.search(/[аеэя]йшыя$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // Суфіксы -івы, -лівы, -чывы (клапатлівы, спагадлівы)
  if (/лівы$/i.test(clean) || /чывы$/i.test(clean)) {
    const idx = clean.search(/[аеіоуыэюя][лч]івы$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 7. Назоўнікавыя суфіксы
  // -анне, -енне, -энне, -янне (рашэнне, пытанне, чытанне)
  if (/[аеэя]нне$/i.test(clean)) {
    const idx = clean.search(/[аеэя]нне$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[аеэя]нні$/i.test(clean)) {
    const idx = clean.search(/[аеэя]нні$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[аеэя]нняў$/i.test(clean)) {
    const idx = clean.search(/[аеэя]нняў$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // -іца, -ыца (ра́ніца, таблі́ца, крыні́ца)
  if (/[іы]ца$/i.test(clean)) {
    return clean.replace(/([іы])ца$/i, '$1\u0301ца');
  }
  if (/[іы]цы$/i.test(clean)) {
    return clean.replace(/([іы])цы$/i, '$1\u0301цы');
  }
  if (/[іы]цу$/i.test(clean)) {
    return clean.replace(/([іы])цу$/i, '$1\u0301цу');
  }
  if (/[іы]цай$/i.test(clean)) {
    return clean.replace(/([іы])цай$/i, '$1\u0301цай');
  }

  // -іна, -ына (краі́на, айчы́на, сцяжы́на, гадзі́на, хвілі́на)
  if (/[іы]на$/i.test(clean)) {
    return clean.replace(/([іы])на$/i, '$1\u0301на');
  }
  if (/[іы]ны$/i.test(clean)) {
    return clean.replace(/([іы])ны$/i, '$1\u0301ны');
  }
  if (/[іы]ну$/i.test(clean)) {
    return clean.replace(/([іы])ну$/i, '$1\u0301ну');
  }
  if (/[іы]най$/i.test(clean)) {
    return clean.replace(/([іы])най$/i, '$1\u0301най');
  }

  // -уля, -улі, -улю (мату́ля, тату́ля, бабу́ля, дзяду́ля)
  if (/уля$/i.test(clean)) {
    return clean.replace(/уля$/i, 'у\u0301ля');
  }
  if (/улі$/i.test(clean)) {
    return clean.replace(/улі$/i, 'у\u0301лі');
  }
  if (/улю$/i.test(clean)) {
    return clean.replace(/улю$/i, 'у\u0301лю');
  }
  if (/уляй$/i.test(clean)) {
    return clean.replace(/уляй$/i, 'у\u0301ляй');
  }

  // -асць, -осць, -есць (радасць, маладосць)
  if (/асць$/i.test(clean)) {
    const stem = clean.slice(0, -4);
    const stemVowels = stem.match(/[аеіоуыэюя]/gi);
    if (!stemVowels || stemVowels.length === 0) {
      return clean.replace(/асць$/i, 'а\u0301сць');
    }
    // Націск на папярэдні галосны
    for (let i = clean.length - 5; i >= 0; i--) {
      if (/[аеіоуыэюя]/i.test(clean[i])) {
        return clean.slice(0, i + 1) + '\u0301' + clean.slice(i + 1);
      }
    }
  }

  // -ства, -цтва (мастацтва, таварыства, кіраўніцтва)
  if (/[сц]тва$/i.test(clean)) {
    for (let i = clean.length - 5; i >= 0; i--) {
      if (/[аеіоуыэюя]/i.test(clean[i])) {
        return clean.slice(0, i + 1) + '\u0301' + clean.slice(i + 1);
      }
    }
  }

  // Прыстаўка па- перад прыслоўямі (па-беларуску, па-руску, па-свойму)
  if (/^па-[а-яёіў]+у$/i.test(clean)) {
    // Націск перад -у
    for (let i = clean.length - 2; i >= 3; i--) {
      if (/[аеіоуыэюя]/i.test(clean[i])) {
        return clean.slice(0, i + 1) + '\u0301' + clean.slice(i + 1);
      }
    }
  }

  // 11. Дзеясловы цяперашняга/будучага часу на -уць/-юць, -уцца/-юцца, -уе/-юе, -уем/-юем, -уеце/-юеце
  if (/[уіыэеяа]юць$/i.test(clean)) {
    const idx = clean.search(/[уіыэеяа]юць$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[уіыэеяа]юцца$/i.test(clean)) {
    const idx = clean.search(/[уіыэеяа]юцца$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[уіыэеяа]е$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[уіыэеяа]е$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }
  if (/[уіыэеяа]ецца$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[уіыэеяа]ецца$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 12. Формы прошлага часу дзеясловаў (-іў/-ыў, -іла/-ыла, -ілі/-ылі, -іць/-ыць)
  if (/[іы]ла$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([іы])ла$/i, '$1\u0301ла');
  }
  if (/[іы]лі$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([іы])лі$/i, '$1\u0301лі');
  }
  if (/[іы]ў$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([іы])ў$/i, '$1\u0301ў');
  }
  if (/[іы]ць$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([іы])ць$/i, '$1\u0301ць');
  }
  if (/[іы]цца$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([іы])цца$/i, '$1\u0301цца');
  }
  if (/[ая]ла$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([ая])ла$/i, '$1\u0301ла');
  }
  if (/[ая]лі$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([ая])лі$/i, '$1\u0301лі');
  }
  if (/[ая]ў$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([ая])ў$/i, '$1\u0301ў');
  }
  if (/[ая]ць$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([ая])ць$/i, '$1\u0301ць');
  }
  if (/[ая]цца$/i.test(clean) && countVowels(clean) >= 2) {
    return clean.replace(/([ая])цца$/i, '$1\u0301цца');
  }

  // 13. Суфіксы -нік, -ніца, -нікам, -нікаў, -нікі
  if (/нік[а-яёіў]*$/i.test(clean)) {
    const idx = clean.search(/[аеіоуыэюя]нік[а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 14. Суфіксы прыметнікаў -аваты, -яваты (ружава́ты, саладкава́ты)
  if (/[ая]ват[ыаеуюі][а-яёіў]*$/i.test(clean) && countVowels(clean) >= 2) {
    const idx = clean.search(/[ая]ват[ыаеуюі][а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 15. Суфіксы -альны, -яльны, -арны, -ярны (нацыяна́льны, рэгуля́рны)
  if (/[ая][лр]ь?н[ыаеуюі][а-яёіў]*$/i.test(clean) && countVowels(clean) >= 3) {
    const idx = clean.search(/[ая][лр]ь?н[ыаеуюі][а-яёіў]*$/i);
    if (idx >= 0) {
      return clean.slice(0, idx + 1) + '\u0301' + clean.slice(idx + 1);
    }
  }

  // 16. Дзеясловы інфінітывы на -сці, -зці, -гчы, -кчы (пайсці́, прыйсці́, знайсці́, памагчы́)
  if (/([сз]ці|[гк]чы)$/i.test(clean)) {
    const vowelMatches = Array.from(clean.matchAll(/[аеёіоуыэюяАЕЁІОУЫЭЮЯ]/g));
    if (vowelMatches.length > 0) {
      const lastVowelIdx = vowelMatches[vowelMatches.length - 1].index;
      if (lastVowelIdx !== undefined) {
        return clean.slice(0, lastVowelIdx + 1) + '\u0301' + clean.slice(lastVowelIdx + 1);
      }
    }
  }

  // 17. Дзеясловы прошлага часу на -шлі, -шла, -шло (пайшла́, пайшлі́, прыйшла́, прыйшлі́)
  if (/ш(лі|ла|ло)$/i.test(clean)) {
    const vowelMatches = Array.from(clean.matchAll(/[аеёіоуыэюяАЕЁІОУЫЭЮЯ]/g));
    if (vowelMatches.length > 0) {
      const lastVowelIdx = vowelMatches[vowelMatches.length - 1].index;
      if (lastVowelIdx !== undefined) {
        return clean.slice(0, lastVowelIdx + 1) + '\u0301' + clean.slice(lastVowelIdx + 1);
      }
    }
  }

  return clean;
}
