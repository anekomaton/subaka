export function splitTextIntoTTSChunks(text: string, maxLen = 150): string[] {
  if (text.length <= maxLen) return [text];
  const parts: string[] = [];
  const sentences = text.match(/[^.!?]+[.!?]+|[^.!?]+$/g) || [text];
  let cur = "";
  for (const s of sentences) {
    if ((cur + " " + s).trim().length <= maxLen) {
      cur = (cur + " " + s).trim();
    } else {
      if (cur) parts.push(cur);
      if (s.length > maxLen) {
        const words = s.split(" ");
        let wCur = "";
        for (const w of words) {
          if ((wCur + " " + w).trim().length <= maxLen) {
            wCur = (wCur + " " + w).trim();
          } else {
            if (wCur) parts.push(wCur);
            wCur = w;
          }
        }
        if (wCur) parts.push(wCur);
        cur = "";
      } else {
        cur = s;
      }
    }
  }
  if (cur) parts.push(cur);
  return parts;
}

export function addStressToSingleVowelWords(text: string): string {
  // Расстаўляем знак націску \u0301 для аднаскладовых паўназначных слоў (Дзе, Не, хто, што, ты, дзе, дом, час...),
  // але НЕ для адналітарных злучнікаў і прыназоўнікаў (а, і, у, ў, о, э, з, к, б, ж), якія з'яўляюцца праклітыкамі.
  return text.replace(/[а-яёіўА-ЯЁІЎ\u0300\u0301]+/gi, (word) => {
    const rawWord = word.replace(/[\u0300\u0301]/g, "");
    // Адналітарныя словы (а, і, у, ў, о, э) не патрабуюць штучнага знака націску
    if (rawWord.length <= 1) return rawWord;
    if (/[\u0300\u0301]/.test(word)) return word;
    // Службовыя аднаскладовыя часціцы і прыназоўнікі
    if (/^(на|па|за|да|ад|пад|над|без|пры|як|ці|бо|жа|бы|б|ж)$/i.test(rawWord)) return word;
    const vowels = rawWord.match(/[аеёіоуыэюяАЕЁІОУЫЭЮЯ]/g);
    if (vowels && vowels.length === 1) {
      return word.replace(/([аеёіоуыэюяАЕЁІОУЫЭЮЯ])/, "$1\u0301");
    }
    return word;
  });
}
