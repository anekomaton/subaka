import { normalizeBelarusianNumbersInText } from './belarusianNumberToWords';
import { convertTextBelG2P } from './belG2P';

/**
 * Спецыялізаванае фанетычнае пераўтварэнне беларускага тэксту і транскрыпцый для ўкраінскага рухавіка TTS (tl=uk).
 * Адаптуе беларускую фанетыку (афрыкаты дз/дж, цеканне ць/ці, нескладовае ў, цвёрдыя ж/ш/ч/р,
 * раздзяляльны апостраф і галосныя, школьную і IPA-транскрыпцыю) так, каб украінскі акустычны
 * сінтэзатар выдаваў максімальна аўтэнтычнае літаратурнае беларускае вымаўленне без памылак і лішніх знакаў.
 */
export function belarusianToUkrainianTTS(text: string): string {
  if (!text) return "";

  // 0. Нармалізацыя лічбаў і лічэбнікаў у беларускія словы
  const textNormalized = normalizeBelarusianNumbersInText(String(text));

  // 1. Ачыстка тэгаў і нармалізацыя прабелаў
  let t = textNormalized.replace(/<[^>]*>/g, "").replace(/\{[^}]*\}/g, "").trim();

  // Калі ўваходны тэкст складаецца з адной асобнай літары (напр. "ж", "ж.", "Б", "г!"),
  // вяртаем літару наўпрост як ёсць. Гэта гарантуе 100% дакладнае вымаўленне без аглушэння
  // у BelG2P (ж -> ш) і без дадання непатрэбнага «ы» (чытанне як «ж», а не «жы»).
  const trimmedInput = t.trim();
  const singleLetterMatch = trimmedInput.match(/^([\p{L}])([.?!,…:;]*)$/u);
  if (singleLetterMatch) {
    return singleLetterMatch[1] + (singleLetterMatch[2] || "");
  }

  // Замяняем кропку пасля адналітарных слоў (напр. "О.", "А.", "І.") на кому,
  // каб Google TTS (tl=uk) не інтэрпрэтаваў іх як украінскія геаграфічныя скарачэнні (напр. "о." -> "острів")
  t = t.replace(/(^|[^\p{L}])([\p{L}])\.(?=\s|[^\p{L}]|$)/giu, "$1$2,");

  // Забяспечваем захаванне націску на апошнім складзе ў займенніках мяне, цябе, сябе, табе
  t = t.replace(/(^|[^\p{L}])мне([\u0300\u0301]?)/giu, "$1мне\u0301")
       .replace(/(^|[^\p{L}])мяне([\u0300\u0301]?)/giu, "$1мяне\u0301")
       .replace(/(^|[^\p{L}])цябе([\u0300\u0301]?)/giu, "$1цябе\u0301")
       .replace(/(^|[^\p{L}])сябе([\u0300\u0301]?)/giu, "$1сябе\u0301")
       .replace(/(^|[^\p{L}])табе([\u0300\u0301]?)/giu, "$1табе\u0301");

  // Праверка, ці з'яўляецца ўваходны радок гатовай фанетычнай транскрыпцыяй (BelG2P школьнай або IPA)
  const isPhoneticInput = /\[.*\]/.test(t) || 
                         /[\u0361\u035F\u035C\u0331\u0332_‿ːˑ]/.test(t) || 
                         /([а-яёіўґ])['’]:/.test(t) || 
                         /[ɣɦɡʐʒʂʃʋβwɫɱɔɛɨɪəɐ]/.test(t) ||
                         /['’ʹʼʻʲ`][аеёіоуыэюяАЕЁІОУЫЭЮЯ]/i.test(t);

  if (!isPhoneticInput) {
    // Для стандартнага беларускага тэксту выкарыстоўваем афіцыйны канвертар BelG2P (G2P),
    // які правільна раскладвае ётаваныя галосныя (напр. прыгожыя -> прыго́жыйа, добрае -> до́брайэ),
    // расстаўляе аўтэнтычныя націскі і асіміляцыю мяккасці.
    try {
      t = convertTextBelG2P(t, { format: "skolny" });
    } catch (g2pErr) {
      console.warn("[BelG2P converter error]:", g2pErr);
    }
  }

  // Аднаўляем пачатковае "і" для слоў тыпу "імя" / "імгненне" / "імпэт" пасля галосных (дзе BelG2P пераводзіць і -> й):
  // У акустычным сінтэзатары (Google TTS tl=uk) формы "йм'а" / "ймя" не пазнаюцца як словы і чытаюцца памылкова як "іма".
  // Перавод у "ім'я́" гарантуе 100% дакладнае, выразнае вымаўленне з націскам [iˈmʲa].
  t = t.replace(/(^|[^\p{L}])(й|Й)м['’ʹʼʻʲ`]?([аеёіоуыэюяАЕЁІОУЫЭЮЯ])/giu, (match, prefix, j, vowel) => {
    const isCap = j === "Й";
    return prefix + (isCap ? "І" : "і") + "м'" + vowel;
  });
  t = t.replace(/(^|[^\p{L}])(й|Й)м([гнпт])/giu, (match, prefix, j, cons) => {
    const isCap = j === "Й";
    return prefix + (isCap ? "І" : "і") + "м" + cons;
  });
  // Дакладны націск на канцы для формы "імя" / "ім'а"
  t = t.replace(/(^|[^\p{L}])(і|І)м['’ʹʼʻʲ`]?([аяАЯ])([\u0300\u0301]?)(?=[^\p{L}]|$)/giu, "$1$2м'я\u0301");

  // Захоўваем цвёрдасць зычных у канчатках -ыя / -ые / -ыю (напр. ахвотныя -> ахво́тны я), каб Google TTS не асіміляваў іх у мяккія ўкраінскія формы (і-я)
  t = t.replace(/([ыЫ])йа/g, "$1 йа").replace(/([ыЫ])йэ/g, "$1 йэ").replace(/([ыЫ])йу/g, "$1 йу");

  // Дадаем "й" да адзінкавых мужчынскіх прыметнікаў на "-ы" (напр. гато́вы -> гато́вый), каб Google TTS не лічыў іх множнымі лікам на "-і" (гатові) і вымаўляў папярэдні зычны цвёрда
  t = t.replace(/([аеёіоуыэюяАЕЁІОУЫЭЮЯ]\u0301[бвгджзклмнпрстфхц])ы(?=[^\p{L}]|$)/giu, "$1ый");

  // Нармалізацыя знакаў націску:
  // пераводзім combining grave (\u0300) і spacing acute (´, \u00B4) у стандартны combining acute (\u0301)
  t = t.replace(/\u0300/g, "\u0301").replace(/\u00B4/g, "\u0301");
  // Апостраф пасля галоснага лічыцца знакам націску (напр. за'мак -> за́мак)
  t = t.replace(/([аеёіоуыэюяАЕЁІОУЫЭЮЯ])['’](?=[а-яёіўА-ЯЁІЎ])/g, "$1\u0301");

  // Літара ё ў беларускай заўсёды пад націскам: здымаем камбінаваны акут з ё,
  // бо ё́ выклікае палітарнае вымаўленне ў Google TTS!
  t = t.replace(/ё\u0301/g, "ё").replace(/Ё\u0301/g, "Ё");

  // Здымаем выпадковыя знакі націску з адналітарных слоў і праклітык (а́, і́, у́, о́, э́),
  // каб Google TTS не чытаў іх як асобныя літары ці «ар»
  t = t.replace(/(^|[^-\p{L}'’ʹʼʻʲ`])([аеёіоуыэюяАЕЁІОУЫЭЮЯ])\u0301(?=[^-\p{L}'’ʹʼʻʲ`]|$)/giu, "$1$2");

  // 2. Пераўтварэнне складаных афрыкат і спалучэнняў з улікам любых лігатурных дужак, падкрэсліванняў і дыякрытык
  t = t.replace(/d[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*z[ʲ\u02B2'’]?/gi, "дзь")
       .replace(/d[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ʒ/gi, "дж")
       .replace(/d[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ʐ/gi, "дж")
       .replace(/d[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*з[ʲ\u02B2'’]?/gi, "дзь")
       .replace(/d[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ж/gi, "дж")
       .replace(/д[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*з[ʲ\u02B2'’]?/gi, "дзь")
       .replace(/д[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ж/gi, "дж")
       .replace(/t[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*s[ʲ\u02B2'’]?/gi, "ць")
       .replace(/t[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ʃ/gi, "ч")
       .replace(/t[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ʂ/gi, "ч")
       .replace(/t[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ц[ʲ\u02B2'’]?/gi, "ць")
       .replace(/t[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ч/gi, "ч")
       .replace(/т[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*с[ʲ\u02B2'’]?/gi, "ць")
       .replace(/т[͡\u0361\u035F\u035C\u0331\u0332_‿⁀⁔-]*ч/gi, "ч");

  // Поўны набор сімвалаў міжнароднага фанетычнага алфавіта (IPA)
  const ipaMap: Record<string, string> = {
    "ɣ": "г", "ɦ": "г", "ɡ": "ґ", "g": "ґ",
    "ʐ": "ж", "ʒ": "ж", "ʂ": "ш", "ʃ": "ш",
    "ʋ": "в", "β": "в", "w": "ў", "u̯": "ў",
    "ɫ": "л", "l": "л", "ɱ": "м", "m": "м",
    "n": "н", "r": "р", "p": "п", "b": "б",
    "t": "т", "d": "д", "k": "к", "x": "х",
    "s": "с", "z": "з", "j": "й", "c": "ц",
    "ɔ": "о", "ɛ": "э", "ɨ": "ы", "ɪ": "ы",
    "ə": "а", "ɐ": "а", "a": "а", "e": "е",
    "i": "і", "o": "о", "u": "у"
  };
  for (const [k, v] of Object.entries(ipaMap)) {
    t = t.split(k).join(v);
  }

  // 3. Падоўжаныя зычныя ў транскрыпцыі (IPA ː, ˑ і міжлітарнае двухкроп'е)
  t = t.replace(/([а-яёіўґ])ь[ːˑ:]/gi, "$1ь$1ь");
  t = t.replace(/([а-яёіўґ])['’ʹʼʻʲ][ːˑ:]/gi, "$1ь$1ь");
  t = t.replace(/([а-яёіўґ])[ːˑ:]/gi, "$1$1");
  t = t.replace(/ь+/g, "ь");

  // 4. Мяккасць у транскрыпцыі: пераўтварэнне спалучэнняў мяккага зычнага перад галоснымі
  t = t.replace(/(дз|дж|ц|[бвгдзклмнпрстфхц])[ь'’ʹʼʻʲ`]+([аАaA])([\u0300\u0301]?)/g, "$1я$3");
  t = t.replace(/(дз|дж|ц|[бвгдзклмнпрстфхц])[ь'’ʹʼʻʲ`]+([уУuU])([\u0300\u0301]?)/g, "$1ю$3");
  t = t.replace(/(дз|дж|ц|[бвгдзклмнпрстфхц])[ь'’ʹʼʻʲ`]+([іІiI])([\u0300\u0301]?)/g, "$1і$3");
  t = t.replace(/(дз|дж|ц|[бвгдзклмнпрстфхц])[ь'’ʹʼʻʲ`]+([оОoO])([\u0300\u0301]?)/g, "$1ё$3");

  // Для дз / Дз выкарыстоўваем надзвычай мяккае "дзіє" (памякчэнне праз і + є), каб акустычны рухавік сінтэзаваў чыстае мяккае [дзе] (дзе, дзеці, надзея, адзенне), а не цвёрдае "дзэ"
  t = t.replace(/(дз|Дз|ДЗ)[ь'’ʹʼʻʲ`]+([эЭeE])([\u0300\u0301]?)/g, (match, char, vowel, stress) => {
    const isCap = char[0] === "Д" && char[1] === "з";
    const isAllCap = char === "ДЗ";
    return (isAllCap ? "ДЗІЄ" : isCap ? "Дзіє" : "дзіє") + (stress || "");
  });
  // Для ц / Ц перад э/е выкарыстоўваем прамое мяккае "тє" / "Тє",
  // якое ў акустычнай мадэлі сінтэзуецца як сапраўднае беларускае мяккае цэканне [це] (хацелі -> хатєлі, цела -> тєла, цесна -> тєсна, ляцелі -> лятєлі), а не цвёрдае ўкраінскае "цэ"
  t = t.replace(/(ц|Ц)[ь'’ʹʼʻʲ`]+([эЭeE])([\u0300\u0301]?)/g, (match, char, vowel, stress) => {
    return (char === "Ц" ? "Тє" : "тє") + (stress || "");
  });
  // Для слоў з коранем сфер- (сфера, сферы, атмасфера, біясфера) захоўваем стандартнае "сфе" без уставак,
  // каб акустычны рухавік не праглынаў пачатковы гук "с" і не вымаўляў "фера"
  t = t.replace(/([сС])ф[ь'’ʹʼʻʲ`]+([эЭeE])([\u0300\u0301]?)/gi, "$1фе$3");
  // Для губных зычных (б, п, в, м) перад е выкарыстоўваем "іє" (біє, піє, віє, міє),
  // каб акустычны рухавік сінтэзаваў сапраўднае беларускае мяккае [е] (цяпер -> цяпер, белы -> белы, песня -> песня), а не цвёрдае "пэ/бэ/вэ"
  t = t.replace(/([бпвмБПВМ])[ь'’ʹʼʻʲ`]+([эЭeE])([\u0300\u0301]?)/g, (match, char, vowel, stress) => {
    return char + "іє" + (stress || "");
  });
  t = t.replace(/(ф|Ф)[ь'’ʹʼʻʲ`]+([эЭeE])([\u0300\u0301]?)/g, "$1е$3");
  // Для язычных і свісцячых (д, з, л, н, с, т) перад е выкарыстоўваем "ьє", каб гучалі мякка
  t = t.replace(/(дж|[дзлмнстДЗЛМНСТ])[ь'’ʹʼʻʲ`]+([эЭeE])([\u0300\u0301]?)/g, "$1ьє$3");

  t = t.replace(/(дз|дж|ц|[бвгдзклмнпрстфхц])[ь'’ʹʼʻʲ`]+([ыЫyY])([\u0300\u0301]?)/g, "$1і$3");

  // 5. Захаванне раздзяляльнага апострафа (сям'я, аб'ява, п'е, з'ява, б'юць, вераб'і)
  const SEP = "\uE000";
  t = t.replace(/([бпвмфздтргкх])['’ʹʼʻ`'']([яеёюіЯЕЁЮІ])/gi, `$1${SEP}$2`);

  // 6. Любыя іншыя апострафы ў транскрыпцыі — гэта знакі мяккасці (')
  t = t.replace(/[’ʹʼʻʲ`'']/g, "'");
  t = t.replace(/([бвгдзклмнпрстфхц])'/gi, "$1ь");
  t = t.replace(/ьь/g, "ь");

  // 7. Падваенні мяккіх зычных у беларускай мове (жыццё, насенне, вяселле, суддзя)
  // Для ўкраінскага TTS мяккі падвоены афрыкат перадаецца выразна як цьц, ньн, сьс, дзьдз
  t = t.replace(/цц([еёюяі])/gi, "цьц$1");
  t = t.replace(/нн([еёюяі])/gi, "ньн$1");
  t = t.replace(/сс([еёюяі])/gi, "сьс$1");
  t = t.replace(/зз([еёюяі])/gi, "зьз$1");
  t = t.replace(/дздз([еёюяі])/gi, "дзьдз$1");

  // Асіміляцыя мяккасці (сьць -> сць, зьдзі -> здзі, сьця -> сця, сьвя -> свя, сьня -> сня)
  t = t.replace(/сьць/g, "сць").replace(/Сьць/g, "Сць").replace(/сьці/g, "сці").replace(/Сьці/g, "Сці");
  t = t.replace(/сьц([яіеєю])/g, "сц$1").replace(/Сьц([яіеєю])/g, "Сц$1");
  t = t.replace(/зьдзі/g, "здзі").replace(/Зьдзі/g, "Здзі");
  t = t.replace(/сьв([яеёію])/gi, "св$1").replace(/сьві/gi, "сві").replace(/Сьві/g, "Сві");
  t = t.replace(/сьн([яеёію])/gi, "сн$1").replace(/сьні/gi, "сні").replace(/Сьні/g, "Сні");
  t = t.replace(/рсьць/gi, "рсть").replace(/рсць/gi, "рсть");
  t = t.replace(/рць/gi, "рть");

  // Выдзяляем прыстаўку зь- перад афрыкатамі дз/дж (напр. здзівіў -> зь-дзівіў), каб акустычны рухавік згарантавана і выразна вымаўляў пачатковы зычны [zʲ]
  t = t.replace(/(^|[^\p{L}])(з|зь)\s*(дзь|дзі|дзе|дзю|дзя|дзё|дж)/giu, "$1зь-$3");

  // Прыназоўнікі: перад глухімі зычнымі (т, к, п, ф, х, с, ц) зліваем у адзінае фанетычнае слова (стабой, скім, спамяццю),
  // каб сінтэзатар вымаўляў чысты зычны гук [с], а не назву асобнай літары "эс"
  t = t.replace(/(^|[^\p{L}])(з|сь|с)['’ʹʼʻʲ`]?\s+([ткпфхсцТКПФХСЦ])/giu, "$1с$3");
  t = t.replace(/(^|[^\p{L}])(з|с|ш)['’ʹʼʻʲ`]?\s+([чшЧШ])/giu, "$1ш$2");
  t = t.replace(/(^|[^\p{L}])(с|сь|ш|ж)['’ʹʼʻʲ`]?\s+([бвгджзклмнпрйаеёіоуыэюяБВГДЖЗКЛМНПРЙАЕЁІОУЫЭЮЯ])/giu, "$1з $3");

  // Перадухіленне памылковай ёфікацыі каранёў (дрэн/нядрэн) у Google TTS:
  // Мадэль Google TTS асацыюе суцэльнае 'дрэнн' з расійскім 'недрёный', таму 'няд-рэ́нны' / 'д-рэ́нны' гарантуе 100% дакладнае вымаўленне [drɛn]
  t = t.replace(/(^|[^\p{L}])(ня|не|Ня|Не)?(дрэ[\u0300\u0301]?н|дрэн)/giu, (match, prefix, neg, root) => {
    const n = neg || "";
    return prefix + (n ? n + "д-рэ\u0301н" : "д-рэ\u0301н");
  });
  t = t.replace(/(^|[^\p{L}])(ня|не|Ня|Не)?(дрэ[\u0300\u0301]?нь|дрэнь)/giu, (match, prefix, neg, root) => {
    const n = neg || "";
    return prefix + (n ? n + "д-рэ\u0301нь" : "д-рэ\u0301нь");
  });

  // Гарантыя цвёрдага вымаўлення [t] у займенніках гэтым, гэта, гэтых, гэтымі, гэту (захоўвае цвёрдасць 'т' без пераходу ў «гэцім»):
  t = t.replace(/(^|[^\p{L}])(гэ|ге)[\u0300\u0301]?ты(м|х|мі)(?=[^\p{L}]|$)/giu, "$1гэ́ ты-$3");
  t = t.replace(/(^|[^\p{L}])(гэ|ге)[\u0300\u0301]?та(?=[^\p{L}]|$)/giu, "$1гэ́ та");
  t = t.replace(/(^|[^\p{L}])(гэ|ге)[\u0300\u0301]?ту(?=[^\p{L}]|$)/giu, "$1гэ́ ту");

  // Размяжоўваем гук "ў" перад зычнымі і постфіксамі (нядаўняй -> нядаў-няй, забыўся -> забыў-ся, заўсёды -> заў-сёды, траўка -> траў-ка, галоўны -> галоў-ны),
  // каб у акустычным сінтэзатары гук "ў" апынуўся ў пазіцыі канца склада (коды) і сінтэзаваўся як чысты білабіяльны [w] (ў кароткае), а не лабіядэнтальны фрыкатыў [v]
  t = t.replace(/([аеёіоуыэюяАЕЁІОУЫЭЮЯ\u0300\u0301])(ў|в|w|u̯)([бвгджзклмнпрстфхцчшщБВГДЖЗКЛМНПРСТФХЦЧШЩ])/gu, "$1$2-$3");

  // Выдаляем любыя пакінутыя лацінскія сімвалы ці тэхнічныя пазнакі
  t = t.replace(/[a-zA-Z]/g, "");

  // 9. Беларускія зацвярдзелыя зычныя (ж, ш, ч, р, дж) — заўсёды цвёрдыя
  const alwaysHard = "жшчрджЖШЧРДЖ";

  // 10. Фанетычная трансфармацыя літар для ўкраінскага акустычнага рухавіка
  let res = "";
  for (let i = 0; i < t.length; i++) {
    const ch = t[i];
    const prev = i > 0 ? t[i - 1] : "";

    if (ch === "ў" || ch === "Ў") {
      const isVowelBefore = prev && "аеёіоуыэюяАЕЁІОУЫЭЮЯ\u0300\u0301".includes(prev);
      if (isVowelBefore) {
        // Пасля галосных (быў, забыўся, пайшоў, аўто, траўка) — гэта нескладовы зычны [w],
        // які перадаецца як "в" (забы́вся, быв, пайшов), каб не ўтвараць штучнага галоснага збегу "ы-у"
        res += (ch === "Ў" ? "В" : "в");
      } else {
        // На пачатку слова ці пасля зычных (ў хаце, ўчора) — "у"
        res += (ch === "Ў" ? "У" : "у");
      }
    } else if (ch === "ы" || ch === "Ы") {
      // Захоўваем літару "ы", каб Google TTS сінтэзаваў сапраўдны цвёрды беларускі [ɨ] (забыўся, быў, рыба),
      // і не пераўтвараў словы ў мяккаватыя ўкраінскія фальшывыя амографы (напр. "забився" -> "забіўся")
      res += ch;
    } else if (ch === "э" || ch === "Э") {
      // Пераводзім беларускае цвёрдае 'э' у стандартную ўкраінскую літару 'е' (вымаўляецца як цвёрдае [ɛ]),
      // каб Google TTS (tl=uk) не пераключаўся на расійскія графічныя правілы (якія счытваюць 'гэтым' як 'гэцім')
      res += (ch === "Э" ? "Е" : "е");
    } else if (ch === "е" || ch === "Е") {
      const isStartOrVowel = !prev || "аеёіоуыэюяАЕЁІОУЫЭЮЯєїи".includes(prev) || /[\s\p{P}]/u.test(prev);
      if (isStartOrVowel) {
        // На пачатку слова ці пасля галосных (ведае, есці, мае, новае) — мяккае ётаванае [je] (укр. "є")
        res += (ch === "Е" ? "Є" : "є");
      } else {
        // Пасля зычных: у беларускай мове літара "е" заўсёды мяккая (вымаўляецца як [je]/[ʲe], а не як цвёрдае ўкраінскае [ɛ]/"э")
        if (alwaysHard.includes(prev)) {
          res += (ch === "Е" ? "Е" : "е"); // пасля зацвярдзелых (ж, ш, ч, р, дж) — цвёрдае [ɛ]
        } else {
          res += (ch === "Е" ? "Є" : "є"); // пасля ўсіх астатніх — заўсёды мяккае [je]/[ʲe] (укр. "є")
        }
      }
    } else if (ch === "ё" || ch === "Ё") {
      const isStartOrVowel = !prev || "аеёіоуыэюяАЕЁІОУЫЭЮЯєїи".includes(prev) || /[\s\p{P}]/u.test(prev);
      if (isStartOrVowel) {
        res += (ch === "Ё" ? "Йо" : "йо");
      } else if (alwaysHard.includes(prev)) {
        res += (ch === "Ё" ? "О" : "о"); // пасля зацвярдзелых (ж, ш, ч, р, дж) — цвёрдае "о", без "ь"
      } else {
        res += (ch === "Ё" ? "Ьо" : "ьо");
      }
    } else {
      res += ch;
    }
  }

  // 11. Аднаўленне раздзяляльнага апострафа для ётаванага вымаўлення ва ўкраінскім рухавіку
  res = res.replace(/\uE000([яЯ])/g, "'я");
  res = res.replace(/\uE000([еЕ])/g, "'є");
  res = res.replace(/\uE000([ёЁ])/g, "'йо");
  res = res.replace(/\uE000([юЮ])/g, "'ю");
  res = res.replace(/\uE000([іІ])/g, "'ї");
  res = res.replace(/\uE000/g, "'");

  // Дзеяслоўнае цеканне на канцы (быць, жыць, рабіць) — пераканаемся, што канчаецца на ць (з улікам магчымага знака націску)
  res = res.replace(/([бвгджзклмнпрстфх])(и[\u0300\u0301]?)ть\b/gi, "$1$2ць");
  res = res.replace(/([бвгджзклмнпрстфх])(а[\u0300\u0301]?)ть\b/gi, "$1$2ць");
  res = res.replace(/([бвгджзклмнпрстфх])(е[\u0300\u0301]?)ть\b/gi, "$1$2ць");
  res = res.replace(/([бвгджзклмнпрстфх])(ы[\u0300\u0301]?)ть\b/gi, "$1$2ць");

  // Забяспечваем аўтэнтычнае цвёрдае вымаўленне беларускага спалучэння "шч" (шчыра, шчасце, шчака) праз украінскую літару "щ",
  // бо ва ўкраінскім акустычным рухавіку літара "щ" абазначае цвёрды кластар [шч], у той час як літарнае "шч" змякчае "ч" перад галоснымі
  res = res.replace(/шч/g, "щ").replace(/Шч/g, "Щ").replace(/ШЧ/g, "Щ");

  // Забяспечваем выразнае вымаўленне пачатковага "с" у спалучэннях сц- / сьц- (напр. сцяжынцы -> зцяжинци, сцерва -> зцієрва, сцяг -> зцяг, сцяна -> зцяна),
  // каб Google TTS не прапускаў пачатковы гук "с" і не чытаў яго як назву літары "эс" (выкарыстоўваем украінскі прыстаўкавы аналаг зц-, які сінтэзуецца як чысты мяккі [сьць])
  res = res.replace(/(^|[^-\p{L}\p{M}'’ʹʼʻʲ`])(сь|Сь|с|С)ц/giu, (match, prefix, char) => {
    const isCap = char[0] === "С";
    return prefix + (isCap ? "Зц" : "зц");
  });

  // Забяспечваем вельмі мяккае і суцэльнае аднаскладовае вымаўленне слоў "мне" (мьнє́) замест украінскага двускладовага "мэне"
  res = res.replace(/(^|[^\p{L}])(м|М)нє([\u0300\u0301]?)(?=[^\p{L}]|$)/giu, "$1$2ьнє$3");

  // 12. Поўная і безумоўная ачыстка ад любых падкрэсленняў, дыякрытык і тэхнічных знакаў
  // Здымаем усе combining macrons, bridges, low lines, underties, ties
  res = res.replace(/[\u035F\u0331\u0332\u0333\u032A\u033A\u031E\u031F\u0320\u032F\u035C\u0361\u0306\u0304ˈˌ]/g, "");
  res = res.replace(/[_＿‿⁀⁔\[\]\(\)\{\}\<\>\\\/|#^~*+=§\u200B\uFEFF]+/g, " ");
  res = res.replace(/\s+/g, " ").trim();

  return res;
}

